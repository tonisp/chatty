export function createTranslator(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return (key, ...args) => {
    const val = dict[key] ?? TRANSLATIONS.en[key] ?? key;
    return typeof val === 'function' ? val(...args) : val;
  };
}
