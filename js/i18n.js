export function createTranslator(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.et;
  return (key, ...args) => {
    const val = dict[key] ?? TRANSLATIONS.et[key] ?? key;
    return typeof val === 'function' ? val(...args) : val;
  };
}
